// ─── Helper: convert Python source to minimal .ipynb ──────────────────────
function generateIPynb(source) {
  // Split on cell markers
  const parts = source.split(/(?=# %% =+\r?\n# CELL \d+)/);
  const cells = parts.filter(p => p.trim()).map(part => ({
    cell_type: 'code',
    execution_count: null,
    metadata: {},
    outputs: [],
    source: part,
  }));
  return JSON.stringify({
    nbformat: 4,
    nbformat_minor: 5,
    metadata: {
      kernelspec: { display_name: 'Python 3', language: 'python', name: 'python3' },
      language_info: { name: 'python', version: '3.10.0' },
    },
    cells,
  });
}

