// ─── Kaggle API helpers ────────────────────────────────────────────────────
function kaggleHeaders(username, key) {
  const token = Buffer.from(`${username}:${key}`).toString('base64');
  return {
    Authorization: `Basic ${token}`,
    'Content-Type': 'application/json',
    'User-Agent': 'vuwee-gen/1.0',
  };
}

