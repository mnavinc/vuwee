// Push notebook to Kaggle and start run
app.post('/api/kaggle/run', async (req, res) => {
  const { username, key, kernelSlug, config } = req.body;
  if (!username || !key || !kernelSlug) {
    return res.status(400).json({ ok: false, message: 'Kaggle Username, API Key, and Kernel Slug are required' });
  }
  try {
    let source;
    try {
      source = buildNotebookSource(config);
    } catch (e) {
      // If template not found, return error with instructions
      return res.status(400).json({ ok: false, message: e.message });
    }

    const payload = {
      slug: `${username}/${kernelSlug}`,
      newTitle: kernelSlug,
      text: generateIPynb(source),
      language: 'python',
      kernelType: 'notebook',
      isPrivate: true,
      enableGpu: true,
      enableTpu: false,
      enableInternet: true,
      datasetDataSources: [],
      competitionDataSources: [],
      kernelDataSources: [],
      modelDataSources: [],
      categoryIds: [],
    };

    const r = await axios.post(
      'https://www.kaggle.com/api/v1/kernels/push',
      payload,
      { headers: kaggleHeaders(username, key), timeout: 60000 }
    );
    res.json({ ok: true, data: r.data });
  } catch (e) {
    const status = e.response?.status;
    const msg = e.response?.data?.message || e.response?.data?.error?.message || e.message;
    res.status(status || 500).json({ ok: false, message: msg });
  }
});

