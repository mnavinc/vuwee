// Download output file from Kaggle to local
app.post('/api/kaggle/download', async (req, res) => {
  const { username, key, kernelSlug, fileName, outputPath } = req.body;
  try {
    // Get output file URL from Kaggle
    const listR = await axios.get(
      'https://www.kaggle.com/api/v1/kernels/output',
      {
        headers: kaggleHeaders(username, key),
        params: { userName: username, kernelSlug },
        timeout: 15000,
      }
    );
    const files = listR.data.files || [];
    const target = files.find(f => f.fileName === (fileName || 'final.mp4'));
    if (!target) {
      return res.status(404).json({ ok: false, message: `File "${fileName || 'final.mp4'}" not found in output` });
    }

    // Download the file
    const savePath = outputPath
      ? path.resolve(outputPath)
      : path.join(DOWNLOADS_DIR, `${kernelSlug}_${Date.now()}_${target.fileName}`);

    const fileR = await axios.get(target.url, {
      headers: kaggleHeaders(username, key),
      responseType: 'stream',
      timeout: 300000,
    });

    const writer = fs.createWriteStream(savePath);
    fileR.data.pipe(writer);
    await new Promise((resolve, reject) => {
      writer.on('finish', resolve);
      writer.on('error', reject);
    });

    res.json({ ok: true, savedPath: savePath, size: fs.statSync(savePath).size });
  } catch (e) {
    res.status(e.response?.status || 500).json({ ok: false, message: e.response?.data?.message || e.message });
  }
});

